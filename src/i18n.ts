type TranslationKey = keyof typeof translations.en;

export const getInitialLanguage = (): Language => {
  const saved = localStorage.getItem('fastbox.language');
  if (saved === 'en' || saved === 'zh') {
    return saved;
  }
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
};

export const createTranslator = (language: Language) => {
  return (key: TranslationKey, params: Params = {}): string => {
    let value: string = translations[language][key] ?? translations.en[key] ?? key;
    for (const [paramKey, paramValue] of Object.entries(params)) {
      value = value.split(`{${paramKey}}`).join(String(paramValue ?? ''));
    }
    return value;
  };
};
